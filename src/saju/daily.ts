// 같은 우리말로 옮겨지는 서로 다른 원문(예: 訂婚·訂盟·納采 → "약혼")을 한 항목으로 합친다.
// 현대 항목을 우선 남기고, 원문 한자는 "訂婚·納采"처럼 모아 붙인다.
function dedupeByKo(terms: DailyTerm[]): DailyTerm[] {
  const byKo = new Map<string, DailyTerm>();
  for (const t of terms) {
    const cur = byKo.get(t.ko);
    if (!cur) {
      byKo.set(t.ko, { ...t });
      continue;
    }
    if (cur.raw !== t.raw && !cur.raw.includes(t.raw)) cur.raw = `${cur.raw}·${t.raw}`;
    if (cur.archaic && !t.archaic) cur.archaic = false; // 현대 항목이 하나라도 있으면 노출
    if (!cur.desc && t.desc) cur.desc = t.desc;
  }
  return [...byKo.values()];
}

