const TRAD_OVERRIDE: Record<string, string> = { 天后: "天后" };

function toTrad(simp: string): string {
  const key = (simp ?? "").trim();
  if (!key || key.startsWith("sn.")) return key;
  if (TRAD_OVERRIDE[key]) return TRAD_OVERRIDE[key];
  let out = "";
  for (const c of key) out += SIMP_TO_TRAD[c] ?? c;
  return out;
}

function toKo(raw: string): DailyTerm {
  const key = (raw ?? "").trim();
  if (!key) return { raw: key, ko: key, desc: "", archaic: false };
  // i18n 키(sn.*)는 원문 표기가 의미 없으므로 raw 도 우리말로 맞춘다.
  if (key.startsWith("sn.")) {
    const ko = TERM_KO[key] ?? key;
    return { raw: ko, ko, desc: descOf(key, ko), archaic: false };
  }
  const trad = toTrad(key); // 원문은 한국식 정체(번체) 한자로
  const merged = YIJI_MERGE[key];
  const archaic = merged ? !MODERN_MERGE.has(merged) : ARCHAIC_YIJI.has(key);
  if (merged) {
    return { raw: trad, ko: merged, desc: descOf(key, merged), archaic };
  }
  if (TERM_KO[key]) {
    const ko = TERM_KO[key];
    return { raw: trad, ko, desc: descOf(key, ko), archaic };
  }
  // 글자 단위 음독. 한 자라도 표에 없으면 정체 원문 유지.
  let out = "";
  for (const ch of key) {
    const r = HANJA_READING[ch];
    if (!r) return { raw: trad, ko: trad, desc: descOf(key, trad), archaic };
    out += r;
  }
  const ko = out || trad;
  return { raw: trad, ko, desc: descOf(key, ko), archaic };
}

