function clampN(n: number, lo: number, hi: number): number {
  return Math.max(lo, Math.min(hi, n));
}

// 오늘 하루의 길흉 강도(-100~+100)를 여러 신호의 가중합으로 산출.
function computeDayStrength(a: {
  tianShen: string; luck: string; jianChu: string;
  jiShen: string[]; xiongSha: string[]; yi: string[];
  dayGan: string; myDayGan?: string;
}): DayStrength {
  const reasons: string[] = [];
  let s = 0;

  // 1) 황도/흑도 (십이신 길흉)
  const isHuang = /吉|黄/.test(a.luck) || HUANG_TIANSHEN.has(a.tianShen);
  s += isHuang ? 25 : -25;
  reasons.push(isHuang ? "황도길일 +25" : "흑도흉일 −25");

  // 2) 건제12신
  const jc = JIANCHU[a.jianChu];
  if (jc) {
    s += jc.score;
    reasons.push(`건제 ${jc.ko}(${jc.trad}) ${jc.score >= 0 ? "+" : "−"}${Math.abs(jc.score)}`);
  }

  // 3) 길신 vs 흉살 (개수 + 상위길신/강흉살 가중)
  let g = clampN(a.jiShen.length * 3, 0, 20) - clampN(a.xiongSha.length * 3, 0, 20);
  const topN = a.jiShen.filter((x) => TOP_JISHEN.has(x)).length;
  const hardN = a.xiongSha.filter((x) => HARD_XIONGSHA.has(x)).length;
  g += topN * 5 - hardN * 5;
  s += g;
  reasons.push(
    `길신 ${a.jiShen.length}·흉살 ${a.xiongSha.length}` +
    `${topN ? ` (상위길신 ${topN})` : ""}${hardN ? ` (강흉살 ${hardN})` : ""} ${g >= 0 ? "+" : "−"}${Math.abs(g)}`
  );

  // 4) 오늘 일진 천간 ↔ 내 일간 (개인층, myDayGan 있을 때만)
  if (a.myDayGan && a.dayGan) {
    const { rel, stars } = seWunScore(a.dayGan, a.myDayGan);
    const r = stars >= 5 ? 15 : stars >= 4 ? 8 : stars <= 1 ? -15 : 0;
    s += r;
    reasons.push(`내 일간과 ${rel} ${r >= 0 ? "+" : "−"}${Math.abs(r)}`);
  }

  // 5) 宜(하면 좋은 일) 리스트 상태
  if (a.yi.includes("无") || a.yi.includes("诸事不宜")) {
    s -= 15;
    reasons.push("마땅한 일 없음 −15");
  } else if (a.yi.includes("馀事勿取")) {
    s -= 8;
    reasons.push("자잘한 일만 있음 −8");
  } else if (a.yi.length >= 10) {
    s += 5;
    reasons.push("길한 일 많음 +5");
  }

  s = clampN(Math.round(s), -100, 100);
  const band: DayBand = s >= 40 ? "대길" : s >= 15 ? "길" : s >= -14 ? "평" : s >= -39 ? "흉" : "대흉";
  const stars = s >= 40 ? 5 : s >= 15 ? 4 : s >= -14 ? 3 : s >= -39 ? 2 : 1;
  return { score: s, pct: Math.round((s + 100) / 2), stars, band, reasons };
}

// getPositionCai/Xi 는 팔괘를, get*Desc 는 방위 한자를 돌려준다. 둘 다 우리말로.
function positionKo(descFns: Array<() => unknown>, triFns: Array<() => unknown>): string {
  for (const f of descFns) {
    const s = dirToKo(safeStr(f));
    if (s) return s;
  }
  for (const f of triFns) {
    const t = safeStr(f).trim();
    if (TRIGRAM_DIR_KO[t]) return TRIGRAM_DIR_KO[t];
  }
  return "";
}

/* ---- lunar-typescript 안전 호출 --------------------------- */

function safeStr(fn: () => unknown): string {
  try {
    const v = fn();
    return v == null ? "" : String(v);
  } catch {
    return "";
  }
}

function safeArr(fn: () => unknown): string[] {
  try {
    const v = fn();
    return Array.isArray(v) ? v.map((x) => String(x)) : [];
  } catch {
    return [];
  }
}

const WEEKDAYS = ["일", "월", "화", "수", "목", "금", "토"];

const KST_YMD = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Seoul",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
});

/** 기준 시각(기본: 지금)을 Asia/Seoul 달력 날짜로 변환. */
export function kstToday(base: Date = new Date()): { year: number; month: number; day: number } {
  const [y, m, d] = KST_YMD.format(base).split("-").map(Number);
  return { year: y, month: m, day: d };
}

/**
 * 오늘(KST) 하루 기준의 일진·택일·신살 정보를 계산한다.
 * @param myDayGan 내 사주 일간(천간 한자). 주면 dayStrength 에 개인층(일진↔일간)이 반영된다.
 */
export function computeDailyInfo(base: Date = new Date(), myDayGan?: string): DailyInfo {
  const { year, month, day } = kstToday(base);
  const lunar = Solar.fromYmdHms(year, month, day, 12, 0, 0).getLunar();

  const dayGanZhi = safeStr(() => lunar.getDayInGanZhi());
  const chongZhi = safeStr(() => lunar.getDayChong());
  const luckRaw = safeStr(() => lunar.getDayTianShenLuck());
  const luck = /吉|黄/.test(luckRaw) ? "길일" : /凶|黑/.test(luckRaw) ? "흉일" : "";

  const jianChuRaw = safeStr(() => lunar.getZhiXing());
  const tianShenRaw = safeStr(() => lunar.getDayTianShen());
  const jiShenRaw = safeArr(() => lunar.getDayJiShen());
  const xiongShaRaw = safeArr(() => lunar.getDayXiongSha());
  const yiRaw = safeArr(() => lunar.getDayYi());
  const jiRaw = safeArr(() => lunar.getDayJi());

  const jc = JIANCHU[jianChuRaw];

  return {
    date: `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`,
    weekday: WEEKDAYS[new Date(year, month - 1, day).getDay()],
    dayGanZhi,
    dayGan: dayGanZhi[0] ?? "",
    dayZhi: dayGanZhi[1] ?? "",
    monthGanZhi: safeStr(() => lunar.getMonthInGanZhi()),
    yearGanZhi: safeStr(() => lunar.getYearInGanZhi()),
    chongZhi,
    chongTti: ZHI_TO_TTI[chongZhi] ?? "",
    jianChu: jc
      ? { raw: jc.trad, ko: jc.ko, desc: jc.desc }
      : { raw: jianChuRaw, ko: jianChuRaw, desc: "" },
    tianShen: toKo(tianShenRaw),
    tianShenLuck: luck,
    jiShen: jiShenRaw.map(toKo),
    xiongSha: xiongShaRaw.map(toKo),
    yi: dedupeByKo(yiRaw.map(toKo)),
    ji: dedupeByKo(jiRaw.map(toKo)),
    positionCai: positionKo(
      [() => lunar.getDayPositionCaiDesc(), () => lunar.getPositionCaiDesc()],
      [() => lunar.getDayPositionCai(), () => lunar.getPositionCai()]
    ),
    positionXi: positionKo(
      [() => lunar.getDayPositionXiDesc(), () => lunar.getPositionXiDesc()],
      [() => lunar.getDayPositionXi(), () => lunar.getPositionXi()]
    ),
    dayStrength: computeDayStrength({
      tianShen: tianShenRaw,
      luck: luckRaw,
      jianChu: jianChuRaw,
      jiShen: jiShenRaw,
      xiongSha: xiongShaRaw,
      yi: yiRaw,
      dayGan: dayGanZhi[0] ?? "",
      myDayGan,
    }),
  };
}

