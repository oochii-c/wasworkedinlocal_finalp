export interface DailyTerm {
  raw: string;      // 원문 용어 — 한국식 정체(번체) 한자
  ko: string;       // 우리말 표기 (없으면 raw 그대로)
  desc: string;     // 이 신살/용어에 대한 한 줄 설명 (없으면 "")
  archaic?: boolean; // 택일(의/기) 중 현대엔 거의 안 하는 항목(사문화·종교 전문)
}

export type DayBand = "대길" | "길" | "평" | "흉" | "대흉";

export interface DayStrength {
  score: number;      // -100 ~ +100 (원점수)
  pct: number;        // 0 ~ 100 (표시용)
  stars: number;      // 1 ~ 5
  band: DayBand;      // 5단계 라벨
  reasons: string[];  // 채점 근거 ("황도 +25" 등)
}

export interface DailyInfo {
  date: string;          // YYYY-MM-DD (Asia/Seoul)
  weekday: string;       // "토"
  dayGanZhi: string;     // 오늘 일진 간지 (甲子)
  dayGan: string;        // 일진 천간
  dayZhi: string;        // 일진 지지
  monthGanZhi: string;   // 이번달 월운
  yearGanZhi: string;    // 올해 세운
  chongZhi: string;      // 충(冲) 지지
  chongTti: string;      // 충 지지의 띠 ("쥐")
  jianChu: DailyTerm;    // 건제12신 (建·除·滿·平…)
  tianShen: DailyTerm;   // 십이신(황도흑도)
  tianShenLuck: string;  // "길일" | "흉일" | ""
  jiShen: DailyTerm[];   // 길신
  xiongSha: DailyTerm[]; // 흉살
  yi: DailyTerm[];       // 오늘 하기 좋은 일
  ji: DailyTerm[];       // 오늘 꺼릴 일
  positionCai: string;   // 재물 방위 (우리말)
  positionXi: string;    // 희신 방위 (우리말)
  dayStrength: DayStrength; // 오늘 하루 길흉 강도 (일간 기준, myDayGan 없으면 개인층 제외)
}

