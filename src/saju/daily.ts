// 방위 한자 문자열을 우리말로. (예: "西南" → "서남", "正東" → "정동")
function dirToKo(s: string): string {
  const key = (s ?? "").trim();
  if (!key) return "";
  if (DIRECTION_KO[key]) return DIRECTION_KO[key];
  const CH: Record<string, string> = { 東: "동", 东: "동", 西: "서", 南: "남", 北: "북", 正: "정", 中: "중" };
  let out = "";
  for (const c of key) out += CH[c] ?? c;
  return out;
}

